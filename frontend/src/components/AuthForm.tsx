import { useState, useEffect } from 'react'
import { useAuth } from '../context/AuthContext'
import { useLanguage } from '../hooks/useLanguage'
import { Terminal, Shield, Cpu, Info } from 'lucide-react'

export default function AuthForm() {
  const { login, register, loginAsDemo } = useAuth()
  const { t, lang, setLang } = useLanguage()
  const [isLoginMode, setIsLoginMode] = useState<boolean>(true)
  const [username, setUsername] = useState<string>('')
  const [password, setPassword] = useState<string>('')
  const [errorMsg, setErrorMsg] = useState<string | null>(null)
  const [isSubmitting, setIsSubmitting] = useState<boolean>(false)

  // Catch telemetry session expiration messages generated by global interceptors
  useEffect(() => {
    const sessionError = localStorage.getItem('al_session_err')
    if (sessionError) {
      // Dynamically extract translation from the localized dictionary mapping matrix
      setErrorMsg(t.authSessionExpired)
    }
  }, [lang, t])

  const handleSubmit = async (e: React.SyntheticEvent) => {
    e.preventDefault()
    if (!username.trim() || !password.trim()) return

    setErrorMsg(null)
    localStorage.removeItem('al_session_err')
    setIsSubmitting(true)

    try {
      if (isLoginMode) {
        await login(username.trim(), password.trim())
      } else {
        await register(username.trim(), password.trim())
      }
    } catch (err: any) {
      setErrorMsg(err.message || 'Authentication sequence failed.')
      setIsSubmitting(false)
    }
  }

  const handleDemoClick = async () => {
    setErrorMsg(null)
    localStorage.removeItem('al_session_err')
    setIsSubmitting(true)
    try {
      await loginAsDemo()
    } catch (err: any) {
      setErrorMsg(err.message || 'Demo initialization failed.')
      setIsSubmitting(false)
    }
  }

  return (
    <div className="flex min-h-screen w-screen items-center justify-center bg-[#020617] px-4 font-mono antialiased selection:bg-emerald-500/20 selection:text-emerald-400">
      <div className="w-full max-w-md rounded-xl border border-slate-800/80 bg-slate-900/40 p-6 shadow-2xl backdrop-blur-md">
        {/* Language Controller Trigger */}
        <button
          type="button"
          onClick={() => setLang(lang === 'en' ? 'ru' : 'en')}
          className="absolute top-4 right-4 cursor-pointer rounded border border-slate-800 bg-slate-950/40 px-2 py-1 text-[10px] font-bold text-slate-400 transition-all hover:border-emerald-500/40 hover:text-emerald-400"
        >
          {lang.toUpperCase()}
        </button>

        <div className="mb-6 flex flex-col items-center text-center">
          <div className="flex h-12 w-12 items-center justify-center rounded-lg border border-emerald-500/20 bg-emerald-500/10 text-emerald-400 shadow-[0_0_15px_rgba(52,211,153,0.15)]">
            <Terminal className="h-6 w-6" />
          </div>
          <h2 className="mt-3 text-lg font-black tracking-wider text-slate-200 uppercase">
            {t.authTitle}
          </h2>
          <p className="mt-1 text-[11px] tracking-tight text-slate-500 uppercase">
            {t.authSubtitle}
          </p>
        </div>

        {errorMsg && (
          <div className="mb-4 flex items-start gap-2.5 rounded-lg border border-rose-950/40 bg-rose-950/10 p-3 text-left">
            <Shield className="mt-0.5 h-4 w-4 shrink-0 text-rose-400" />
            <div className="flex flex-col">
              <span className="text-[10px] font-bold tracking-wider text-rose-400 uppercase">
                {t.authErrorHeader}
              </span>
              <p className="mt-0.5 text-[11px] leading-relaxed text-slate-400">
                {errorMsg}
              </p>
            </div>
          </div>
        )}

        {/* Operational Form Workspace */}
        <form onSubmit={handleSubmit} className="space-y-5">
          <div className="flex flex-col gap-2">
            <label className="text-xs font-bold tracking-widest text-slate-400 uppercase">
              {t.authUsernameLabel}
            </label>
            <input
              type="text"
              value={username}
              onChange={(e) => setUsername(e.target.value)}
              disabled={isSubmitting}
              required
              placeholder="e.g., recruiter-tech-lead"
              className="w-full rounded-lg border border-slate-800 bg-slate-950/60 px-3.5 py-3 text-sm text-slate-200 placeholder-slate-600 transition-all outline-none focus:border-emerald-500/50 focus:bg-slate-950"
            />
          </div>

          <div className="flex flex-col gap-2">
            <label className="text-xs font-bold tracking-widest text-slate-400 uppercase">
              {t.authPasswordLabel}
            </label>
            <input
              type="password"
              value={password}
              onChange={(e) => setPassword(e.target.value)}
              disabled={isSubmitting}
              required
              placeholder="••••••••"
              className="w-full rounded-lg border border-slate-800 bg-slate-950/60 px-3.5 py-3 text-sm text-slate-200 placeholder-slate-600 transition-all outline-none focus:border-emerald-500/50 focus:bg-slate-950"
            />
          </div>

          {!isLoginMode && (
            <div className="flex items-start gap-3 rounded-lg border border-amber-500/10 bg-amber-500/5 p-3.5 text-left">
              <Info className="mt-0.5 h-4 w-4 shrink-0 text-amber-400" />
              <div className="flex flex-col">
                <span className="text-xs font-bold tracking-wider text-amber-400 uppercase">
                  {t.authNoticeHeader}
                </span>
                <p className="mt-1 text-xs leading-relaxed text-slate-400">
                  {t.authNoticeBody}
                </p>
              </div>
            </div>
          )}

          <button
            type="submit"
            disabled={isSubmitting}
            className="flex w-full cursor-pointer items-center justify-center rounded-lg border border-emerald-500/30 bg-emerald-500/10 py-3 text-sm font-bold tracking-wider text-emerald-400 uppercase transition-all hover:bg-emerald-500/20 active:scale-[0.99] disabled:pointer-events-none disabled:opacity-40"
          >
            {isSubmitting ? (
              <div className="h-4 w-4 animate-spin rounded-full border-b-2 border-emerald-400" />
            ) : isLoginMode ? (
              t.authBtnLogin
            ) : (
              t.authBtnRegister
            )}
          </button>
        </form>

        {/* Authorization Mode Alternate Layout Switcher Toggle */}
        <div className="mt-4 text-center">
          <button
            type="button"
            disabled={isSubmitting}
            onClick={() => {
              setIsLoginMode(!isLoginMode)
              setErrorMsg(null)
            }}
            className="cursor-pointer text-xs text-slate-400 underline decoration-slate-600 transition-colors hover:text-emerald-400 hover:decoration-emerald-400 disabled:pointer-events-none"
          >
            {isLoginMode ? t.authToggleRegister : t.authToggleLogin}
          </button>
        </div>

        {/* Dedicated Recruiter Isolation Boundary Section */}
        <div className="mt-5 border-t border-slate-800/80 pt-5">
          <div className="mb-4 flex items-center justify-between gap-3 text-[10px] tracking-widest text-slate-600 uppercase">
            <div className="h-px flex-1 bg-slate-800/40" />
            <span>{t.authDividerOr}</span>
            <div className="h-px flex-1 bg-slate-800/40" />
          </div>

          {/* Sandbox FinOps Fast Track (Demo Access Trigger) */}
          <button
            type="button"
            onClick={handleDemoClick}
            disabled={isSubmitting}
            className="group flex w-full cursor-pointer items-center justify-center gap-2 rounded-lg border border-slate-800 bg-slate-950/40 py-3 text-sm font-semibold text-slate-300 transition-all hover:border-emerald-500/30 hover:bg-slate-950/20 hover:text-emerald-400 hover:shadow-[0_0_15px_rgba(52,211,153,0.05)] active:scale-[0.99] disabled:pointer-events-none disabled:opacity-40"
          >
            <Cpu className="h-4 w-4 text-slate-500 transition-colors group-hover:text-emerald-400" />
            <span>{t.authBtnDemo}</span>
          </button>
        </div>
      </div>
    </div>
  )
}
